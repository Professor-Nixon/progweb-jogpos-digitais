// Operadores Aritméticos

let n1 = 200
let n2 = 5

let adicao = n1 + n2
let subtracao = n1 - n2
let multiplicacao = n1 * n2
let divisao = n1 / n2
let resto = n1 % n2

console.log(`${n1} + ${n2} = ${adicao}`)
console.log(`${n1} - ${n2} = ${subtracao}`)
console.log(`${n1} * ${n2} = ${multiplicacao}`)
console.log(`${n1} / ${n2} = ${divisao}`)
console.log(`${n1} % ${n2} = ${resto}`)